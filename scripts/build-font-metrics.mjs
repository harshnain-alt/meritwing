// Writes src/lib/resume/helvetica-metrics.json: the advance width of every character the PDF's
// standard Helvetica fonts can show, in thousandths of the font size, read from jsPDF's own
// font metrics. The resume layout measures text with this table, so the on-screen preview and
// the exported PDF wrap and align identically. Run: node scripts/build-font-metrics.mjs
import { writeFileSync } from "node:fs";
import { jsPDF } from "jspdf";

const doc = new jsPDF({ unit: "pt", format: "a4" });
const chars = [];
for (let c = 0x20; c <= 0x7e; c++) chars.push(String.fromCharCode(c));
for (let c = 0xa0; c <= 0xff; c++) chars.push(String.fromCharCode(c));
chars.push(..."€‚ƒ„…†‡ˆ‰Š‹ŒŽ‘’“”•–—˜™š›œžŸ");

const out = { note: "Advance widths in 1/1000 em from jsPDF's Helvetica metrics. Generated by scripts/build-font-metrics.mjs.", fonts: {} };
for (const style of ["normal", "bold", "italic"]) {
  doc.setFont("helvetica", style);
  out.fonts[style] = Object.fromEntries(chars.map((ch) => [ch, Math.round(doc.getStringUnitWidth(ch) * 1000)]));
}
writeFileSync(new URL("../src/lib/resume/helvetica-metrics.json", import.meta.url), JSON.stringify(out));
console.log(`wrote ${chars.length} characters x 3 styles`);
